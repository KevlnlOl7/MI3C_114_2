    public String getSource(){
        String html = "";
        try{
            String part1 = "https://www.google.com.tw/search?hl=zh-TW&q=";
            String qString = URLEncoder.encode(queryTf.getText(),"utf-8");
            String part2 = "&meta=&aq=f&gws_rd=ssl";
            URL url = new URL(part1+qString+part2) ;
            System.out.println(url.toExternalForm());
            HttpsURLConnection uc = (HttpsURLConnection) url.openConnection();
            uc.addRequestProperty("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36)");
            try(BufferedReader br = new BufferedReader(new InputStreamReader(uc.getInputStream(), "UTF-8"))){
                StringBuilder temp = new StringBuilder();
                String line;
                while ((line = br.readLine()) != null) {
                    temp.append(line);
                }
                html = temp.toString();
            }catch(Exception e){
                e.printStackTrace();
            }
        }catch(Exception e){
            e.printStackTrace();
        }
        return html;
    }
    public static String getSource(String path){
        File f = new File(path);
        StringBuilder sb = new StringBuilder();
        try(BufferedReader br = new BufferedReader(new FileReader(f))){
            String aLine = "";
            while((aLine = br.readLine()) != null){
                sb.append(aLine).append("\n");
            }
        }catch (Exception e){
            e.printStackTrace();
        }
        return sb.toString();
    } 

