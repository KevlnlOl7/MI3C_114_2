    public void doSearch(String htmlTXT){
        new Thread(() -> {
            try {
                String html = getSource(htmlTXT);
                StringTokenizer st = new StringTokenizer(html, "<>=\" ", true);
                int state = 0;
                boolean rlt = false;
                String header = "", url = "";
                String destFileName = String.format("%s%s", htmlTXT.substring(0, htmlTXT.indexOf('.')) , "_url.txt");
                File f = new File(destFileName);
                try(PrintWriter pw = new PrintWriter(f)){
                    while (st.hasMoreTokens()) {
                        String token = st.nextToken();
                        if (token.equals(" ")) continue; 
                        switch (state) {
                            case 0: 
                                if (token.equalsIgnoreCase("a")) {
                                    url = ""; header = ""; rlt = false;
                                    state = 1;
                                }
                                break;

                            case 1: 
                                if (token.equals("jsname")) state = 2;
                                else if (token.equals("href")) state = 3;
                                else if (token.equals(">")) {

                                    if (rlt && !url.isEmpty()) state = 4;
                                    else state = 0;
                                }
                                break;

                            case 2: 
                                if (token.equalsIgnoreCase("UWckNb")) {
                                    rlt = true;
                                    state = 1;
                                }
                                break;

                            case 3:
                                if (token.equals("\"")) {
                                    StringBuilder sb = new StringBuilder();
                                    while (st.hasMoreTokens()) {
                                        String part = st.nextToken();
                                        if (part.equals("\"")) break; 
                                        sb.append(part);
                                    }
                                    url = sb.toString();
                                    state = 1;
                                }
                                break;

                            case 4: 
                                if (token.equalsIgnoreCase("h3")) state = 5;
                                else if (token.equals("/")) state = 0; 
                                break;

                            case 5: 
                                if (token.equals(">")) {
                                    StringBuilder sb = new StringBuilder();
                                    while (st.hasMoreTokens()) {
                                        String part = st.nextToken();
                                        if (part.equals("<")) break;
                                        sb.append(part);
                                    }
                                    header = sb.toString().trim();


                                    if (!header.isEmpty() && url.startsWith("http")) {
                                        rltTa.append("# " + header + "\n");
                                        rltTa.append(url + "\n");
                                        rltTa.append("--------------------------------------\n");
                                        pw.print(String.format("#%s\n%s\n--------------------------------------\n", header, url));
                                    }
                                    state = 0;
                                }
                                break;
                        }
                    }
                }
                
            } catch (Exception e) {
                rltTa.append(e.getMessage());
            }
        }).start();
    }
